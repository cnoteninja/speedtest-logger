#!/usr/bin/env python3
"""
speed_report: chart your speedlog.csv into a shareable HTML report.

SVG line chart of download speed over time, latency overlay, outage table
(any test under --slow-mbps is flagged), and summary stats.

Usage:
    python speed_report.py [--csv speedlog.csv] [--out speed.html] [--slow-mbps 10]

Zero third-party dependencies.
"""

import argparse
import csv
import html
import os
from datetime import datetime

CSV_DEFAULT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "speedlog.csv")


def num(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return None


def load(path):
    rows = []
    with open(path, newline="", encoding="utf-8") as fh:
        for r in csv.DictReader(fh):
            r["_t"] = r.get("timestamp", "")
            rows.append(r)
    return rows


def svg_chart(rows, slow):
    W, H, PAD = 900, 260, 36
    speeds = [(i, num(r.get("download_mbps"))) for i, r in enumerate(rows)]
    speeds = [(i, v) for i, v in speeds if v is not None]
    if not speeds:
        return "<p>No successful speed tests to chart.</p>"
    vmax = max(v for _, v in speeds) * 1.15 or 1
    n = len(rows)

    def x(i):
        return PAD + (W - 2 * PAD) * (i / max(1, n - 1))

    def y(v):
        return H - PAD - (H - 2 * PAD) * (v / vmax)

    pts = " ".join("%.1f,%.1f" % (x(i), y(v)) for i, v in speeds)
    area = "%.1f,%d %s %.1f,%d" % (x(speeds[0][0]), H - PAD, pts,
                                   x(speeds[-1][0]), H - PAD)
    slow_y = y(min(slow, vmax))
    dots = "".join(
        "<circle cx='%.1f' cy='%.1f' r='4' fill='#dc3545'><title>%s: %s Mbps</title></circle>"
        % (x(i), y(v), html.escape(rows[i].get("timestamp", "")[:16]), v)
        for i, v in speeds if v < slow)
    labels = "".join(
        "<text x='%.1f' y='%d' font-size='10' text-anchor='middle'>%s</text>" % (
            x(i), H - 12, html.escape(rows[i].get("timestamp", "")[11:16]))
        for i in range(0, n, max(1, n // 12)))
    return (
        "<svg viewBox='0 0 %d %d' width='100%%'>"
        "<polygon points='%s' fill='#cce5ff' opacity='0.6'/>"
        "<polyline points='%s' fill='none' stroke='#007bff' stroke-width='2'/>"
        "<line x1='%d' y1='%.1f' x2='%d' y2='%.1f' stroke='#dc3545' stroke-dasharray='5,4'/>"
        "<text x='%d' y='%.1f' font-size='11' fill='#dc3545'>slow threshold (%s Mbps)</text>"
        "%s%s</svg>"
        % (W, H, area, pts, PAD, slow_y, W - PAD, slow_y, PAD + 4, slow_y - 6,
           slow, dots, labels))


def main():
    ap = argparse.ArgumentParser(description="Chart speedlog.csv")
    ap.add_argument("--csv", default=CSV_DEFAULT)
    ap.add_argument("--out", default="speed.html")
    ap.add_argument("--slow-mbps", type=float, default=10.0,
                    help="flag tests below this as slow/outage")
    args = ap.parse_args()

    if not os.path.exists(args.csv):
        print("no data: run speedlog.py first")
        raise SystemExit(1)
    rows = load(args.csv)
    if not rows:
        print("empty csv")
        raise SystemExit(1)

    speeds = [num(r.get("download_mbps")) for r in rows]
    speeds = [s for s in speeds if s is not None]
    lats = [num(r.get("latency_ms")) for r in rows]
    lats = [v for v in lats if v is not None]
    slow_rows = [r for r in rows
                 if (num(r.get("download_mbps")) or 1e9) < args.slow_mbps
                 or not r.get("download_mbps")]

    def stat(vals, f="%.1f"):
        return (f % (sum(vals) / len(vals))) if vals else "n/a"

    slow_table = "".join(
        "<tr><td>%s</td><td>%s</td><td>%s</td><td>%s</td></tr>" % (
            html.escape(r.get("timestamp", "")[:16]),
            html.escape(r.get("label", "")),
            r.get("download_mbps") or "<b>failed</b>",
            html.escape(r.get("error", "")))
        for r in slow_rows)

    page = """<!DOCTYPE html><html><head><meta charset="utf-8">
<title>Internet Speed Report</title>
<style>body{{font-family:system-ui,sans-serif;max-width:1000px;margin:2em auto;padding:0 1em}}
table{{border-collapse:collapse;width:100%}}th,td{{border:1px solid #ddd;padding:.4em .6em;text-align:left}}
th{{background:#f5f5f5}}.kpi{{display:flex;gap:1em}}.kpi div{{border:1px solid #ddd;border-radius:8px;padding:.8em 1.2em}}
.kpi b{{font-size:1.4em}}</style></head><body>
<h1>Internet Speed Report</h1>
<p>{n} tests from {a} to {b}</p>
<div class="kpi">
<div><b>{avg}</b><br>avg Mbps</div>
<div><b>{mn}</b><br>min Mbps</div>
<div><b>{mx}</b><br>max Mbps</div>
<div><b>{lat}</b><br>avg ping ms</div>
<div><b>{slow_n}</b><br>slow/failed tests</div>
</div>
<h2>Download speed over time</h2>
{chart}
<h2>Slow / failed tests (&lt; {thr} Mbps)</h2>
<table><tr><th>Time</th><th>Label</th><th>Mbps</th><th>Note</th></tr>{slowt}</table>
<p><small>Generated by <a href="https://github.com/cnoteninja/speedtest-logger">speedtest-logger</a></small></p>
</body></html>""".format(
        n=len(rows), a=html.escape(rows[0].get("timestamp", "")[:16]),
        b=html.escape(rows[-1].get("timestamp", "")[:16]),
        avg=stat(speeds), mn="%.1f" % min(speeds) if speeds else "n/a",
        mx="%.1f" % max(speeds) if speeds else "n/a", lat=stat(lats),
        slow_n=len(slow_rows), chart=svg_chart(rows, args.slow_mbps),
        thr=args.slow_mbps,
        slowt=slow_table or "<tr><td colspan=4>none — connection held up</td></tr>")

    outdir = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(outdir, os.path.basename(args.out))
    with open(out, "w", encoding="utf-8") as fh:
        fh.write(page)
    print("wrote %s (%d tests, %d slow/failed)" % (out, len(rows), len(slow_rows)))


if __name__ == "__main__":
    main()
