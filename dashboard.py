#!/usr/bin/env python3
"""
dashboard: local read-only web dashboard for speedtest-logger.

Single page, stdlib only (http.server): latest result, uptime % from the
outage analysis, recent outage windows, and the same SVG chart
speed_report.py renders — reused directly, not rewritten.

Read-only: it only serves GET requests; nothing in the page can change
state. Binds to 127.0.0.1 by default (localhost only, no auth needed).

Usage:
    python dashboard.py                    # build dashboard.html from speedlog.csv
    python dashboard.py --serve            # serve it at http://127.0.0.1:8000/
    python dashboard.py --serve --port 8123 --host 127.0.0.1
    python dashboard.py --demo            # sample data, ~30s to see everything
    python dashboard.py --demo --serve    # sample data + sample outage report + serve

Zero third-party dependencies.
"""

import argparse
import html
import http.server
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from speed_report import svg_chart, num  # noqa: E402
from outage_report import load, summarize, fmt_dt, render_markdown, render_html  # noqa: E402
from demo_data import write_csv as demo_csv, describe as demo_describe  # noqa: E402

CSV_DEFAULT = os.path.join(HERE, "speedlog.csv")

STYLE = ("<style>body{font-family:system-ui,sans-serif;max-width:1000px;"
         "margin:2em auto;padding:0 1em}"
         "table{border-collapse:collapse;width:100%}"
         "th,td{border:1px solid #ddd;padding:.4em .6em;text-align:left}"
         "th{background:#f5f5f5}.kpi{display:flex;gap:1em;flex-wrap:wrap}"
         ".kpi div{border:1px solid #ddd;border-radius:8px;padding:.8em 1.2em}"
         ".kpi b{font-size:1.4em}.demo{background:#fff3cd;border:1px solid #ffe08a;"
         "border-radius:8px;padding:.6em 1em;margin-bottom:1em}</style>")


def latest_kpi(rows):
    r = rows[-1]
    mbps = num(r.get("download_mbps"))
    lat = num(r.get("latency_ms"))
    dns = num(r.get("dns_ms"))
    if mbps is None:
        speed = "<b>failed</b> — " + html.escape(r.get("error", "")[:60])
    else:
        speed = "<b>%.1f Mbps</b>" % mbps
    return ("<div><b>%s</b><br>latest result (%s)</div>"
            "<div><b>%s</b><br>ping</div>"
            "<div><b>%s</b><br>DNS</div>" % (
                speed, html.escape(r.get("timestamp", "")[:16]),
                "%.1f ms" % lat if lat is not None else "n/a",
                "%.1f ms" % dns if dns is not None else "n/a"))


def outage_table(windows, limit=5):
    recent = sorted(windows, key=lambda w: w["start"], reverse=True)[:limit]
    rows = []
    for w in recent:
        status = "<b>ongoing</b>" if w["ongoing"] else "closed"
        rows.append("<tr><td>%s</td><td>%s</td><td>%.0f min</td><td>%s</td></tr>"
                    % (fmt_dt(w["start"]), fmt_dt(w["end"]),
                       w["duration"].total_seconds() / 60, status))
    if not rows:
        rows = ["<tr><td colspan=4>none — no outage windows</td></tr>"]
    return ("<table><tr><th>Start (UTC)</th><th>End (UTC)</th>"
            "<th>Duration</th><th>Status</th></tr>" + "".join(rows) + "</table>")


def render_page(rows, s, slow_mbps, is_demo):
    label = " — " + html.escape(s["label"]) if s["label"] else ""
    banner = ("<div class='demo'><b>DEMO</b> — sample data, not real "
              "measurements.</div>" if is_demo else "")
    return """<!DOCTYPE html><html><head><meta charset="utf-8">
<meta http-equiv="refresh" content="300">
<title>Speedtest Dashboard</title>%s</head><body>%s
<h1>Internet Speed Dashboard%s</h1>
<p>%d tests from %s to %s</p>
<div class="kpi">
%s
<div><b>%.2f%%</b><br>uptime</div>
<div><b>%.0f min</b><br>total outage</div>
<div><b>%d</b><br>outage windows</div>
<div><b>%d</b><br>degradation episodes</div>
</div>
<h2>Download speed over time</h2>
%s
<h2>Recent outages</h2>
%s
<p><small>Auto-refreshes every 5 min. Generated by
<a href="https://github.com/cnoteninja/speedtest-logger">speedtest-logger</a> —
read-only, nothing here can change your data.</small></p>
</body></html>""" % (
        STYLE, banner, label, s["n_tests"], fmt_dt(s["first"]),
        fmt_dt(s["last"]), latest_kpi(rows), s["uptime"],
        s["outage_minutes"], len(s["windows"]), len(s["episodes"]),
        svg_chart(rows, slow_mbps), outage_table(s["windows"]))


def no_data_page():
    return ("<!DOCTYPE html><html><head><meta charset='utf-8'>"
            "<title>Speedtest Dashboard</title>%s</head><body>"
            "<h1>Internet Speed Dashboard</h1>"
            "<p>No data yet. Run <code>python speedlog.py</code> to start "
            "logging, or try <code>python dashboard.py --demo</code> for a "
            "sample.</p></body></html>" % STYLE)


def serve(host, port, rows, s, slow_mbps, is_demo):
    if rows:
        page = render_page(rows, s, slow_mbps, is_demo).encode("utf-8")
    else:
        page = no_data_page().encode("utf-8")

    class Handler(http.server.BaseHTTPRequestHandler):
        server_version = "speedtest-logger/1.0"

        def do_GET(self):
            if self.path not in ("/", "/index.html"):
                self.send_error(404, "not found")
                return
            body = page
            self.send_response(200)
            self.send_header("Content-Type", "text/html; charset=utf-8")
            self.send_header("Content-Length", str(len(body)))
            self.send_header("Cache-Control", "no-cache")
            self.end_headers()
            self.wfile.write(body)

        def log_message(self, fmt, *a):
            sys.stderr.write("[dashboard] " + fmt % a + "\n")

    srv = http.server.HTTPServer((host, port), Handler)
    print("dashboard at http://%s:%d/  (Ctrl+C to stop, read-only)" % (
        host, srv.server_address[1]))
    try:
        srv.serve_forever()
    except KeyboardInterrupt:
        pass


def main():
    ap = argparse.ArgumentParser(description="Local web dashboard (stdlib only)")
    ap.add_argument("--serve", action="store_true",
                    help="run an HTTP server instead of writing dashboard.html")
    ap.add_argument("--host", default="127.0.0.1",
                    help="bind address (default 127.0.0.1 = localhost only)")
    ap.add_argument("--port", type=int, default=8000)
    ap.add_argument("--csv", default=CSV_DEFAULT)
    ap.add_argument("--demo", action="store_true",
                    help="use synthetic sample data (no real tests needed)")
    ap.add_argument("--gap-minutes", type=float, default=15.0)
    ap.add_argument("--min-mbps", type=float, default=50.0)
    ap.add_argument("--consecutive", type=int, default=6)
    ap.add_argument("--slow-mbps", type=float, default=10.0,
                    help="chart's slow threshold, same as speed_report.py")
    ap.add_argument("--out", default="dashboard.html",
                    help="static page filename when not using --serve")
    args = ap.parse_args()

    is_demo = args.demo
    if args.demo:
        csv_path = demo_csv(label="demo")
        print("demo data: %s" % demo_describe())
        # sample outage report alongside the sample dashboard
        import tempfile
        demo_dir = tempfile.mkdtemp(prefix="speedtest-demo-")
        rows = load(csv_path)
        s_demo = summarize(rows, args.gap_minutes, args.min_mbps,
                           args.consecutive)
        mdp = os.path.join(demo_dir, "outage_report-demo.md")
        htp = os.path.join(demo_dir, "outage-demo.html")
        with open(mdp, "w", encoding="utf-8") as fh:
            fh.write(render_markdown(s_demo))
        with open(htp, "w", encoding="utf-8") as fh:
            fh.write(render_html(s_demo))
        print("sample outage report -> %s, %s" % (mdp, htp))
    elif os.path.exists(args.csv):
        csv_path = args.csv
    else:
        csv_path = None

    rows = load(csv_path) if csv_path else []
    s = summarize(rows, args.gap_minutes, args.min_mbps,
                  args.consecutive) if rows else None

    if args.serve:
        serve(args.host, args.port, rows, s, args.slow_mbps, is_demo)
    else:
        out = os.path.join(HERE, os.path.basename(args.out))
        with open(out, "w", encoding="utf-8") as fh:
            fh.write(render_page(rows, s, args.slow_mbps, is_demo)
                     if rows else no_data_page())
        print("wrote %s" % out)


if __name__ == "__main__":
    main()
